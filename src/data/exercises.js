/**
 * Verilen hareket adını (AI'dan gelen) veritabanında arar.
 * Kısmi eşleşmeyi de destekler.
 */
export const findExercise = (name) => {
  if (!name) return null;
  const lower = name.toLowerCase().trim();
  return exercises.find((ex) =>
    ex.names.some((n) => lower.includes(n.toLowerCase()) || n.toLowerCase().includes(lower))
  ) || null;
};
